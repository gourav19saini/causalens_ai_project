"""
report_generation.py
---------------------
Builds downloadable CSV and HTML summary reports from the results the app
already computed. No new numbers are calculated here -- this module only
formats existing results, plus assumptions/limitations text.
"""

from __future__ import annotations

import io
from datetime import datetime
from typing import List, Optional

import pandas as pd


def build_csv_report(
    dataset_info: dict,
    config: dict,
    estimator_name: str,
    ate: float,
    ate_ci,
    policy_summary: dict,
    assumptions: List[str],
    limitations: List[str],
) -> bytes:
    rows = []
    rows.append(["Report generated", datetime.now().isoformat(timespec="seconds")])
    rows.append([])
    rows.append(["=== Dataset Information ==="])
    for k, v in dataset_info.items():
        rows.append([k, v])
    rows.append([])
    rows.append(["=== Configuration ==="])
    for k, v in config.items():
        rows.append([k, v])
    rows.append([])
    rows.append(["=== Causal Effect Estimate ==="])
    rows.append(["Estimator used", estimator_name])
    rows.append(["ATE (Average Treatment Effect)", ate])
    if ate_ci is not None:
        rows.append(["95% CI lower", ate_ci[0]])
        rows.append(["95% CI upper", ate_ci[1]])
    rows.append([])
    rows.append(["=== Policy Summary (Model-Based Targeting) ==="])
    for k, v in policy_summary.items():
        rows.append([k, v])
    rows.append([])
    rows.append(["=== Causal Assumptions ==="])
    for a in assumptions:
        rows.append([a])
    rows.append([])
    rows.append(["=== Limitations ==="])
    for l in limitations:  # noqa: E741
        rows.append([l])

    buf = io.StringIO()
    pd.DataFrame(rows).to_csv(buf, index=False, header=False)
    return buf.getvalue().encode("utf-8")


def build_html_report(
    dataset_info: dict,
    config: dict,
    estimator_name: str,
    ate: float,
    ate_ci,
    cate_summary: Optional[dict],
    policy_summary: dict,
    policy_comparison_df: Optional[pd.DataFrame],
    assumptions: List[str],
    limitations: List[str],
    warnings: List[str],
) -> str:
    def _list_html(items):
        return "".join(f"<li>{i}</li>" for i in items) if items else "<li>None</li>"

    def _dict_table(d):
        rows = "".join(f"<tr><td><b>{k}</b></td><td>{v}</td></tr>" for k, v in d.items())
        return f"<table>{rows}</table>"

    cate_html = ""
    if cate_summary:
        cate_html = f"""
        <h2>CATE Summary</h2>
        {_dict_table(cate_summary)}
        """

    comparison_html = ""
    if policy_comparison_df is not None:
        comparison_html = f"""
        <h2>Policy Comparison</h2>
        {policy_comparison_df.to_html(index=False)}
        """

    html = f"""
    <html>
    <head>
    <meta charset="utf-8">
    <title>CausaLens AI - Causal Analysis Report</title>
    <style>
        body {{ font-family: 'Segoe UI', Arial, sans-serif; margin: 40px; color: #1a1a2e; }}
        h1 {{ color: #4B3F72; border-bottom: 3px solid #4B3F72; padding-bottom: 8px; }}
        h2 {{ color: #6C63FF; margin-top: 28px; }}
        table {{ border-collapse: collapse; width: 100%; margin: 10px 0 20px 0; }}
        td, th {{ border: 1px solid #ddd; padding: 8px 12px; text-align: left; }}
        tr:nth-child(even) {{ background-color: #f7f7fb; }}
        .banner {{ background: #FFF4E5; border-left: 5px solid #FFA726; padding: 12px 16px; margin: 16px 0; }}
        .footer {{ margin-top: 40px; font-size: 0.85em; color: #666; }}
    </style>
    </head>
    <body>
        <h1>CausaLens AI &mdash; Causal Analysis Report</h1>
        <p>Generated: {datetime.now().strftime("%Y-%m-%d %H:%M:%S")}</p>

        <div class="banner">
            <b>Important:</b> This report presents estimated causal effects under explicit
            statistical assumptions. It does not constitute proof of real-world causality,
            especially when based on observational and/or synthetic data.
        </div>

        <h2>Dataset Information</h2>
        {_dict_table(dataset_info)}

        <h2>Configuration</h2>
        {_dict_table(config)}

        <h2>Causal Effect Estimate</h2>
        {_dict_table({
            "Estimator used": estimator_name,
            "ATE (Average Treatment Effect)": round(ate, 4),
            "95% CI": f"({ate_ci[0]:.4f}, {ate_ci[1]:.4f})" if ate_ci else "Not available",
        })}

        {cate_html}

        <h2>Policy Recommendation Summary</h2>
        {_dict_table(policy_summary)}

        {comparison_html}

        <h2>Causal Assumptions</h2>
        <ul>{_list_html(assumptions)}</ul>

        <h2>Warnings</h2>
        <ul>{_list_html(warnings)}</ul>

        <h2>Limitations</h2>
        <ul>{_list_html(limitations)}</ul>

        <div class="footer">
            Generated by CausaLens AI &mdash; Automated Causal Inference &amp; Policy
            Optimization Engine. Built for educational / hackathon demonstration purposes.
        </div>
    </body>
    </html>
    """
    return html
